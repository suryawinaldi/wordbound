const LEVEL_MIN_SCORE = { A1: 0, A2: 80, B1: 220, B2: 420, C1: 680, C2: 1000 }

/** Menentukan level CEFR otomatis dari skor kumulatif pemain (bukan dipilih manual). */
export function autoLevelFromScore(score) {
  let lvl = 'A1'
  for (const l of LEVELS) {
    if ((score || 0) >= LEVEL_MIN_SCORE[l]) lvl = l
  }
  return lvl
}

export function nextLevelInfo(score) {
  const cur = autoLevelFromScore(score)
  const idx = LEVELS.indexOf(cur)
  if (idx === LEVELS.length - 1) return { next: null, needed: 0 }
  const next = LEVELS[idx + 1]
  return { next, needed: LEVEL_MIN_SCORE[next] - (score || 0) }
}

function bankFor(contentType) {
  return contentType === 'sentence' ? SENTENCE_ITEMS : WORD_ITEMS
}

export function itemsUpToLevel(contentType, level) {
  const cutoff = LEVELS.indexOf(level) >= 0 ? LEVELS.indexOf(level) : LEVELS.length - 1
  const allowed = LEVELS.slice(0, cutoff + 1)
  return bankFor(contentType).filter((it) => allowed.includes(it.level))
}

function shuffle(arr) {
  const a = [...arr]
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1))
    ;[a[i], a[j]] = [a[j], a[i]]
  }
  return a
}

/** Membangun kumpulan soal acak sejumlah `count`, disesuaikan level, tanpa duplikat. */
export function buildPool(contentType, level, count) {
  const pool = shuffle(itemsUpToLevel(contentType, level))
  return pool.slice(0, count)
}

/** Membuat 4 opsi pilihan ganda (1 benar + 3 pengecoh) dari bank yang sama. */
export function buildChoices(contentType, correctItem) {
  const bank = bankFor(contentType).filter((it) => it.text !== correctItem.text)
  const decoys = shuffle(bank).slice(0, 3)
  return shuffle([correctItem, ...decoys])
}

function levenshtein(a, b) {
  const dp = Array.from({ length: a.length + 1 }, (_, i) => [i, ...Array(b.length).fill(0)])
  for (let j = 0; j <= b.length; j++) dp[0][j] = j
  for (let i = 1; i <= a.length; i++) {
    for (let j = 1; j <= b.length; j++) {
      dp[i][j] = a[i - 1] === b[j - 1] ? dp[i - 1][j - 1] : 1 + Math.min(dp[i - 1][j - 1], dp[i - 1][j], dp[i][j - 1])
    }
  }
  return dp[a.length][b.length]
}

function normalize(s) {
  return s.trim().toLowerCase().replace(/[.,!?;:'"]/g, '').replace(/\s+/g, ' ')
}

/** Menilai jawaban ketikan untuk kata TUNGGAL: correct | close | wrong. */
function judgeWord(guess, answer) {
  const dist = levenshtein(normalize(guess), normalize(answer))
  if (dist === 0) return 'correct'
  if (dist <= 2) return 'close'
  return 'wrong'
}

/** Menilai jawaban ketikan untuk KALIMAT, berbasis persentase kata yang cocok (toleran typo kecil). */
function judgeSentence(guess, answer) {
  const gWords = normalize(guess).split(' ').filter(Boolean)
  const aWords = normalize(answer).split(' ').filter(Boolean)
  if (gWords.length === 0) return 'wrong'
  let matched = 0
  const used = Array(gWords.length).fill(false)
  aWords.forEach((aw) => {
    let bestI = -1
    let bestD = Infinity
    gWords.forEach((gw, i) => {
      if (used[i]) return
      const d = levenshtein(gw, aw)
      if (d < bestD) {
        bestD = d
        bestI = i
      }
    })
    if (bestI !== -1 && bestD <= Math.max(1, Math.floor(aw.length * 0.3))) {
      used[bestI] = true
      matched += 1
    }
  })
  const pct = matched / aWords.length
  if (pct >= 0.95) return 'correct'
  if (pct >= 0.7) return 'close'
  return 'wrong'
}

export function judgeTyped(contentType, guess, answer) {
  return contentType === 'sentence' ? judgeSentence(guess, answer) : judgeWord(guess, answer)
}
